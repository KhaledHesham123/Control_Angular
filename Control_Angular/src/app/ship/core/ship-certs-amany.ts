function cert(issuer: string, issue = '', last = '', due = '', exp = ''): CertSeedValues[string] {
  return {
    issuer,
    issueDate: issue ? dmy(issue) : '',
    lastInsp: last ? dmy(last) : '',
    dueDate: due ? dmy(due) : '',
    expiryDate: exp ? dmy(exp) : '',
  };
}

function dated(qty: string, exp = ''): CertSeedValues[string] {
  return { qty, expiryDate: exp ? dmy(exp) : '' };
}

